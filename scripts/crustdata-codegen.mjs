#!/usr/bin/env node
/** docs/crustdata/openapi/<spec>.yaml → src/lib/crustdata/generated/<spec>.ts (openapi-typescript). */
import fs from "node:fs";
import path from "node:path";
import openapiTS, { astToString } from "openapi-typescript";

const IN = path.join(process.cwd(), "docs/crustdata/openapi");
const OUT = path.join(process.cwd(), "src/lib/crustdata/generated");
const HEADER = "/* eslint-disable */\n// Generated by scripts/crustdata-codegen.mjs from docs/crustdata/openapi — do not edit by hand.\n\n";

fs.mkdirSync(OUT, { recursive: true });
for (const f of fs.readdirSync(IN).filter((x) => x.endsWith(".yaml"))) {
  const ast = await openapiTS(new URL(`file://${path.join(IN, f)}`));
  const out = path.join(OUT, f.replace(/\.yaml$/, ".ts"));
  fs.writeFileSync(out, HEADER + astToString(ast));
  console.log(`wrote ${path.relative(process.cwd(), out)}`);
}
